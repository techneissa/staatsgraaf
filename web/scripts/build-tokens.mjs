#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const WEB_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const TOKENS_PATH = join(WEB_DIR, "..", "shared", "tokens.json");
const OUT_DIR = join(WEB_DIR, "app", "generated");
const OUT_PATH = join(OUT_DIR, "tokens.css");

const HEX = /^#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$/;
const CSS_VALUE = /^[a-zA-Z0-9 (),.%'"#/-]+$/;

function fail(message) {
  console.error(`build-tokens: ${message}`);
  process.exit(1);
}

function assertRecord(value, path) {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    fail(`${path} must be an object`);
  }
  return value;
}

function assertColor(value, path) {
  if (typeof value !== "string" || !HEX.test(value)) {
    fail(`${path} must be a hex colour, got ${JSON.stringify(value)}`);
  }
  return value;
}

function assertValue(value, path) {
  if (typeof value !== "string" || value.length === 0 || !CSS_VALUE.test(value)) {
    fail(`${path} is not a usable CSS value: ${JSON.stringify(value)}`);
  }
  return value;
}

let tokens;
try {
  tokens = JSON.parse(readFileSync(TOKENS_PATH, "utf8"));
} catch (error) {
  fail(`cannot read ${TOKENS_PATH}: ${error.message}`);
}

const color = assertRecord(tokens.color, "color");
const themes = Object.keys(color);
if (!themes.includes("dark")) fail("color.dark is required because dark is the default theme");
for (const theme of themes) {
  for (const [key, value] of Object.entries(assertRecord(color[theme], `color.${theme}`))) {
    assertColor(value, `color.${theme}.${key}`);
  }
}

const font = assertRecord(tokens.font, "font");
const text = assertRecord(tokens.text, "text");
const leading = assertRecord(tokens.leading, "leading");
const tracking = assertRecord(tokens.tracking, "tracking");
const space = assertRecord(tokens.space, "space");
const radius = assertRecord(tokens.radius, "radius");
const border = assertRecord(tokens.border, "border");
const motion = assertRecord(tokens.motion, "motion");
const duration = assertRecord(motion.duration, "motion.duration");
const easing = assertRecord(motion.easing, "motion.easing");

for (const [group, values] of Object.entries({ font, text, leading, tracking, space, radius, border, duration, easing })) {
  for (const [key, value] of Object.entries(values)) {
    assertValue(value, `${group}.${key}`);
  }
}

const lines = [];
lines.push("/*");
lines.push(" * Generated by web/scripts/build-tokens.mjs from shared/tokens.json.");
lines.push(" * Do not edit by hand. Change the token file and rerun `npm run tokens`.");
lines.push(" */");
lines.push("");

function themeBlock(selector, values, theme) {
  lines.push(`${selector} {`);
  for (const key of Object.keys(values)) {
    lines.push(`  --t-color-${key}: ${assertColor(values[key], `color.${theme}.${key}`)};`);
  }
  lines.push("}");
  lines.push("");
}

themeBlock(":root", color.dark, "dark");
for (const theme of themes) {
  if (theme === "dark") continue;
  themeBlock(`[data-theme="${theme}"]`, color[theme], theme);
}

lines.push(":root {");
for (const [key, value] of Object.entries(font)) lines.push(`  --t-font-${key}: ${value};`);
for (const [key, value] of Object.entries(text)) lines.push(`  --t-text-${key}: ${value};`);
for (const [key, value] of Object.entries(leading)) lines.push(`  --t-leading-${key}: ${value};`);
for (const [key, value] of Object.entries(tracking)) lines.push(`  --t-tracking-${key}: ${value};`);
for (const [key, value] of Object.entries(space)) lines.push(`  --t-space-${key}: ${value};`);
for (const [key, value] of Object.entries(radius)) lines.push(`  --t-radius-${key}: ${value};`);
for (const [key, value] of Object.entries(border)) lines.push(`  --t-border-${key}: ${value};`);
for (const [key, value] of Object.entries(duration)) lines.push(`  --t-duration-${key}: ${value};`);
for (const [key, value] of Object.entries(easing)) lines.push(`  --t-ease-${key}: ${value};`);
lines.push("}");
lines.push("");

lines.push("@theme inline {");
for (const key of Object.keys(color.dark)) lines.push(`  --color-${key}: var(--t-color-${key});`);
for (const key of Object.keys(font)) lines.push(`  --font-${key}: var(--t-font-${key});`);
for (const key of Object.keys(text)) lines.push(`  --text-${key}: var(--t-text-${key});`);
for (const key of Object.keys(leading)) lines.push(`  --leading-${key}: var(--t-leading-${key});`);
for (const key of Object.keys(tracking)) lines.push(`  --tracking-${key}: var(--t-tracking-${key});`);
for (const key of Object.keys(space)) lines.push(`  --spacing-${key}: var(--t-space-${key});`);
for (const key of Object.keys(radius)) lines.push(`  --radius-${key}: var(--t-radius-${key});`);
for (const key of Object.keys(easing)) lines.push(`  --ease-${key}: var(--t-ease-${key});`);
lines.push("  --spacing: var(--t-space-1);");
lines.push("  --default-transition-duration: var(--t-duration-base);");
lines.push("}");
lines.push("");

for (const [key] of Object.entries(border)) {
  lines.push(`@utility border-${key} {`);
  lines.push(`  border-width: var(--t-border-${key});`);
  lines.push("}");
  lines.push("");
}
for (const [key] of Object.entries(duration)) {
  lines.push(`@utility transition-${key} {`);
  lines.push(`  transition-duration: var(--t-duration-${key});`);
  lines.push("}");
  lines.push("");
}

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_PATH, `${lines.join("\n").trimEnd()}\n`);
console.log(`build-tokens: wrote ${OUT_PATH} (${themes.length} themes, ${Object.keys(color.dark).length} colour tokens)`);
